# 与前端设计系统一致的强调色（不锈钢色），让文档与系统看起来是一套东西
ACCENT = RGBColor(0x2C, 0x7A, 0x7B)
MUTED = RGBColor(0x5B, 0x66, 0x72)
DANGER = RGBColor(0xB4, 0x23, 0x18)


def set_cjk_font(run, name="微软雅黑"):
    """python-docx 设置中文字体需要动 w:eastAsia，否则中文会回退成宋体。"""
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def h1(doc, text):
    p = doc.add_heading(level=1)
    run = p.add_run(text)
    set_cjk_font(run, "微软雅黑")
    run.font.size = Pt(18)
    run.font.color.rgb = ACCENT
    return p


def h2(doc, text):
    p = doc.add_heading(level=2)
    run = p.add_run(text)
    set_cjk_font(run, "微软雅黑")
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(0x14, 0x18, 0x1D)
    return p


def para(doc, text, size=10.5, bold=False, color=None, space_after=6):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_cjk_font(run)
    run.font.size = Pt(size)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color
    p.paragraph_format.space_after = Pt(space_after)
    return p


def bullet(doc, text, size=10.5):
    p = doc.add_paragraph(style="List Bullet")
    run = p.add_run(text)
    set_cjk_font(run)
    run.font.size = Pt(size)
    p.paragraph_format.space_after = Pt(3)
    return p


def qa(doc, question, short_answer, details=None, code_hint=None):
    """一个问题块：问题（标题）+ 15 秒答案（加粗）+ 展开细节。"""
    h2(doc, f"Q{qa.counter}：{question}")
    qa.counter += 1
    para(doc, f"15 秒答案：{short_answer}", bold=True, color=ACCENT)
    for line in (details or []):
        bullet(doc, line)
    if code_hint:
        para(doc, f"现场演示路径：{code_hint}", size=9.5, color=MUTED)
    para(doc, "", space_after=2)


qa.counter = 1


