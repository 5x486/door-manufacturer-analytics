# -*- coding: utf-8 -*-
"""
HR 视角问答 Word 生成脚本
=========================
    python tools/make_interview_docx.py

产物：reports/面试问答_杭博门业经营分析系统.docx

为什么要生成 Word 而不是写 Markdown：
  求职场景里，面试官/HR 不一定会打开仓库看 README，但会打开你发过去的 Word。
  这份文档的设计原则是「假设你明天要去面试，今晚只能看一份东西」：
    · 每个问题先给 15 秒能说完的答案（加粗），再给可以展开的细节；
    · 诚实标注数据是模拟的，并给出「方向性结论仍成立」的理由；
    · 每个数字都能在系统里点到（指标字典 / 数据质量 / 明细数据三个页面）。
"""
