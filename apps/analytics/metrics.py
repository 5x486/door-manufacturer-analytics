def _metric(
    code,
    name,
    domain,
    metric_type,
    definition,
    formula,
    numerator_desc,
    denominator_desc,
    unit,
    caveat,
    order,
    source_tables=None,
    version="v1",
):
    """构造一条指标定义，统一补默认值，避免每条都写重复字段。"""
    return {
        "code": code,
        "name": name,
        "domain": domain,
        "metric_type": metric_type,
        "definition": definition,
        "formula": formula,
        "numerator_desc": numerator_desc,
        "denominator_desc": denominator_desc,
        "unit": unit,
        "source_tables": list(source_tables or DEFAULT_SOURCE_TABLES.get(domain, [])),
        "caveat": caveat,
        "version": version,
        "order": order,
    }


