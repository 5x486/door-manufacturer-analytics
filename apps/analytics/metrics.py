"""指标口径字典（单一事实来源）。

为什么要把「指标定义」写成代码里的常量
------------------------------------
经营分析系统最大的风险不是算错，而是**同一个词在两处含义不同**：
销售说的「成交额」含运费，财务说的「成交额」不含；看板上的「毛利率」
用明细口径，导出的 Excel 用订单口径。半年之后没人说得清哪个对。

因此本项目把指标定义固化成 :data:`METRIC_DEFINITIONS`：

- 页面上的「指标说明」弹窗、导出的表头注释、``sync_metrics`` 命令写入
  ``MetricDefinition`` 表的内容，全部来自这一份常量；
- 每条定义都带 ``caveat``（易误读提醒）。这不是客套话，「准时率」不排除
  未交付订单就会系统性偏低，「客单价」用订单数还是客户数做分母会差一倍，
  这些坑必须在定义里点名，否则一定会有人踩。

字段约定
--------
- ``code``：``M_<域前缀>_<三位序号>``，稳定不变（改名不改码）；
- ``metric_type``：``amount``(金额) / ``count``(数量) / ``ratio``(比率) /
  ``index``(指数) / ``growth``(增长率)；
- ``unit``：``元`` / ``单`` / ``人`` / ``天`` / ``%`` / ``指数``。
  **比率类指标的单位统一写 ``%``，但存储值是 0~1 的小数**，
  展示时乘 100，这一点在每条 ratio 指标的 definition 里都会重复说明，
  因为它是本项目指标口径最重要的约定；
- ``caveat``：这条指标最容易被误读的地方。

域划分（7 个，与导航模块一一对应）
--------------------------------
经营总览 / 增长渠道 / 品类利润 / 客户价值 / 交付售后 / 回款现金 / 人效门店
"""

